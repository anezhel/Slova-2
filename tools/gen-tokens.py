#!/usr/bin/env python3
"""Generate src/theme/tokens.css from a Figma variables export (tools/figma-tokens.json).

The export is produced in Figma (collections Theme + Spacing, text styles, effects).
Usage:  python3 tools/gen-tokens.py
Each Theme mode becomes one theme:  classic-light, classic-dark, festival.
Components never use colors directly — only these CSS variables.
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'tools', 'figma-tokens.json')
OUT = os.path.join(ROOT, 'src', 'theme', 'tokens.css')

d = json.load(open(SRC, encoding='utf-8'))
modes = d['modes']  # ['classic-light', 'classic-dark', 'festival']
WEIGHT = {'Thin': 100, 'ExtraLight': 200, 'Light': 300, 'Regular': 400, 'Medium': 500,
          'SemiBold': 600, 'Bold': 700, 'ExtraBold': 800, 'Black': 900}
FONT_STACK = {'Manrope': "'Manrope', system-ui, -apple-system, sans-serif",
              'Onest': "'Onest', system-ui, -apple-system, sans-serif"}
PX = {'effect/card-blur', 'effect/card-shadow-radius', 'effect/card-shadow-y',
      'hatch/line-width', 'layout/nav-active-x'}


def css_name(n):
    return '--' + re.sub(r'[^a-z0-9]+', '-', n.lower()).strip('-')


def theme_block(i):
    out = []
    for name, vals in sorted(d['theme'].items()):
        v = vals[i]
        if name == 'font/family':
            out.append(f'  --font: {FONT_STACK.get(v, repr(v))};')
        elif name.startswith('font/style-'):
            out.append(f'  --fw-{name.split("font/style-")[1]}: {WEIGHT[v]};')
        elif name == 'theme/backdrop':
            out.append(f'  --show-backdrop: {"block" if v else "none"};')
        elif name == 'theme/nav-label':
            out.append(f'  --show-nav-label: {"inline" if v else "none"};')
        elif name == 'theme/hatch':
            img = ('repeating-linear-gradient(135deg, var(--bg-hatch-line) 0 var(--hatch-line-width), '
                   'transparent var(--hatch-line-width) 7px)') if v else 'none'
            out.append(f'  --hatch-image: {img};')
        elif name in PX:
            out.append(f'  {css_name(name)}: {v}px;')
        else:
            out.append(f'  {css_name(name)}: {v};')
    return '\n'.join(out)


lines = ['/* GENERATED by tools/gen-tokens.py from the Figma file (collection Theme). Do not edit by hand. */',
         '/* Theme is chosen in src/config.js: festival | classic-light | classic-dark | classic (follows the phone). */', '']
sel = {'classic-light': ':root, [data-theme="classic-light"], [data-theme="classic"]',
       'classic-dark': '[data-theme="classic-dark"]', 'festival': '[data-theme="festival"]'}
for i, m in enumerate(modes):
    lines.append(f'{sel[m]} {{\n{theme_block(i)}\n}}\n')
lines.append('@media (prefers-color-scheme: dark) {\n  [data-theme="classic"] {\n' +
             theme_block(modes.index('classic-dark')) + '\n  }\n}\n')

# spacing, radius, layout
sp = ['/* Spacing (collection Spacing) */', ':root {']
for name, v in d['spacing'].items():
    sp.append(f'  {css_name(name)}: {v}px;')
sp.append('}\n')
lines += sp

# text styles -> font shorthands + classes
ts = ['/* Text styles */', ':root {']
classes = []
for s in d['textStyles']:
    n = s['n']
    key = css_name(n)[2:]
    lh = s['lh']
    lh = 'normal' if lh == 'auto' else (str(round(float(lh[:-1]) / 100, 3)) if str(lh).endswith('%') else f'{lh}px')
    if s['fam'] == 'font/family':
        weight = f"var(--fw-{s['st'].split('font/style-')[1]})"
        fam = 'var(--font)'
    else:
        weight = str(WEIGHT[s['st']])
        fam = FONT_STACK.get(s['fam'], s['fam'])
        if n.startswith('Phonetic'):
            # Neither Manrope nor Onest has IPA glyphs; the system font (SF Pro on iPhone) has them all.
            fam = "system-ui, -apple-system, 'Segoe UI', Roboto, 'Noto Sans', sans-serif"
    ts.append(f'  --font-{key}: {weight} {s["size"]}px/{lh} {fam};')
    ls = s['ls']
    ls = f'{round(float(ls[:-1]) / 100 * s["size"], 2)}px' if isinstance(ls, str) and ls.endswith('%') else f'{round(float(ls), 2)}px'
    ts.append(f'  --ls-{key}: {ls};')
    up = ' text-transform: uppercase;' if s.get('tc') == 'UPPER' else ''
    classes.append(f'.t-{key} {{ font: var(--font-{key}); letter-spacing: var(--ls-{key});{up} }}')
ts.append('}\n')
lines += ts + classes + ['']

# effect styles
lines += ['/* Effect styles */', ':root {',
          '  --shadow-card: 0 var(--effect-card-shadow-y) var(--effect-card-shadow-radius) var(--effect-shadow-card);',
          '  --shadow-nav: 0 12px 30px var(--effect-shadow-nav);',
          '  --shadow-selected: 0 2px 8px var(--effect-shadow-selected);',
          '  --glow-orb: 0 0 0 14px var(--effect-glow-1), 0 0 0 30px var(--effect-glow-2), 0 24px 60px var(--effect-glow-3);',
          '  --glass-blur: blur(var(--effect-card-blur));',
          '}', '']
open(OUT, 'w', encoding='utf-8').write('\n'.join(lines))
print('wrote', OUT)
