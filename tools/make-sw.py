#!/usr/bin/env python3
"""Write sw.js: the list of files the phone keeps for offline use + a version made from their contents.
Run after any change:  python3 tools/make-sw.py   (the new version reaches phones on the next launch)."""
import hashlib, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP_DIRS = {'tools', '.git', '.github', 'node_modules'}
SKIP_FILES = {'sw.js', 'README.md', '.DS_Store', 'LICENSE.md'}

files, h = [], hashlib.sha256()
for d, dirs, names in os.walk(ROOT):
    dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS and not x.startswith('.'))
    for n in sorted(names):
        if n in SKIP_FILES or n.startswith('.'):
            continue
        p = os.path.join(d, n)
        rel = os.path.relpath(p, ROOT).replace(os.sep, '/')
        files.append(rel)
        h.update(rel.encode()); h.update(open(p, 'rb').read())

version = h.hexdigest()[:10]
urls = ',\n  '.join(repr('./' + f if f != 'index.html' else './') for f in files)
sw = f"""// GENERATED by tools/make-sw.py — offline cache for vocca. Version changes when any file changes.
const VERSION = 'vocca-{version}';
const FILES = [
  {urls}
];

self.addEventListener('install', (e) => {{
  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(FILES.map((u) => new Request(u, {{ cache: 'reload' }})))).then(() => self.skipWaiting()));
}});

// Only vocca's own old caches are removed: other apps on the same github.io address keep theirs.
self.addEventListener('activate', (e) => {{
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('vocca-') && k !== VERSION).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
}});

// Cache first (works without internet); falls back to the network for anything new.
self.addEventListener('fetch', (e) => {{
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(caches.match(req, {{ ignoreSearch: true }}).then((hit) => hit || fetch(req).then((res) => {{
    if (res.ok) {{ const copy = res.clone(); caches.open(VERSION).then((c) => c.put(req, copy)); }}
    return res;
  }}).catch(() => caches.match('./'))));
}});
"""
open(os.path.join(ROOT, 'sw.js'), 'w', encoding='utf-8').write(sw)
print('sw.js', version, len(files), 'files')
